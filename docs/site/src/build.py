def bundle_facts():
    """The shipped bundle's manifest and the sensor calibration, read from Resources/, each artifact re-hashed."""
    import hashlib
    res = REPO / "Sources" / "VeilGardeInference" / "Resources"
    out = {}
    manifest = res / "manifest.json"
    if manifest.is_file():
        m = json.loads(manifest.read_text(encoding="utf-8"))
        for a in m.get("artifacts", []):
            p = res / a.get("file", "")
            a["onDisk"] = p.is_file()
            a["matches"] = p.is_file() and hashlib.sha256(p.read_bytes()).hexdigest() == a.get("sha256") and p.stat().st_size == a.get("bytes")
        out["manifest"] = dict(path=manifest.relative_to(REPO).as_posix(), bytes=manifest.stat().st_size, **m)
    cal = res / "warp_sensor_calibration.json"
    if cal.is_file():
        out["calibration"] = dict(path=cal.relative_to(REPO).as_posix(), bytes=cal.stat().st_size, **json.loads(cal.read_text(encoding="utf-8")))
    comb = res / "stack_combiner_v2.json"
    if comb.is_file():
        out["combiner"] = dict(path=comb.relative_to(REPO).as_posix(), **json.loads(comb.read_text(encoding="utf-8")))
    # Each booster's shape, read from its XGBoost JSON: trees, the deepest tree, features.
    boosters = {}
    for key, name in [("warpTile", "warp_tile32.xgb.json"), ("fusionHead", "fusion_head.xgb.json"), ("fusionRef", "fusion_ref.xgb.json")]:
        f = res / name
        if not f.is_file():
            continue
        model = json.loads(f.read_text(encoding="utf-8"))["learner"]
        trees = model["gradient_booster"]["model"]["trees"]
        def depth(tree, node=0):
            left, right = tree["left_children"][node], tree["right_children"][node]
            return 0 if left == -1 else 1 + max(depth(tree, left), depth(tree, right))
        boosters[key] = {"file": name, "trees": len(trees), "depth": max(depth(t) for t in trees),
                         "features": int(model["learner_model_param"]["num_feature"])}
    out["boosters"] = boosters
    out["frozenRoles"] = frozen_roles()
    return out


def frozen_roles():
    """The roles ArtifactRole.isFrozen returns true for, read from Artifact.swift's text; None when its shape moved."""
    path = REPO / "Sources" / "VeilGardeCore" / "Bundle" / "Artifact.swift"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None
    enum = re.search(r"enum ArtifactRole[^{]*\{(.*?)\n\}", text, re.S)
    rule = re.search(r"var isFrozen: Bool \{.*?case ([^:]+): return true", text, re.S)
    if not enum or not rule:
        return None
    raw = {name: value or name for name, value in re.findall(r"\bcase (\w+)(?: = \"([^\"]+)\")?", enum.group(1))}
    roles = [raw.get(c.strip().lstrip("."), None) for c in rule.group(1).split(",")]
    return {"source": "Sources/VeilGardeCore/Bundle/Artifact.swift", "roles": roles} if all(roles) else None


def head_facts():
    """The commit the data was built on, the commits before it, and whether the tree had moved past it. Built on a
    branch with no commit yet, as for a repository's first commit, there is none of them: the data is that commit's."""
    if git("rev-parse", "--verify", "-q", "HEAD", check=False).strip() == "":
        return {"commit": "", "short": "", "dirty": False, "commits": [], "first": True}
    head = git("rev-parse", "HEAD").strip()
    dirty = bool(git("status", "--porcelain", "--untracked-files=normal", "--", ".", ":(exclude)docs/site/data").strip())
    commits = []
    for line in git("log", "--reverse", "--format=%H%x09%ad%x09%s", "--date=short", "HEAD").splitlines():
        h, d, s = line.split("\t", 2)
        commits.append({"commit": h, "short": h[:7], "date": d, "subject": s})
    return {"commit": head, "short": head[:7], "dirty": dirty, "commits": commits}


