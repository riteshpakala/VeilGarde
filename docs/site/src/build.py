def _private_key_block():
    # Spelled in pieces so this file never holds the marker it looks for.
    return "-----BEGIN " + r"(?:[A-Z0-9]+ )*" + "PRIV" + "ATE KEY-----"


KEY_SHAPES = [
    ("an AWS access key id", re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b")),
    ("an sk- API key", re.compile(r"\bsk-(?:ant-|proj-|live-|test-)?[A-Za-z0-9_\-]{20,}")),
    ("a GitHub token", re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}|\bgithub_pat_[A-Za-z0-9_]{30,}")),
    ("a Slack token", re.compile(r"\bxox[abposr]-[A-Za-z0-9-]{10,}")),
    ("a Google API key", re.compile(r"\bAIza[0-9A-Za-z_\-]{35}")),
    ("a private key block", re.compile(_private_key_block())),
]
TOKEN = re.compile(r"(?<![A-Za-z0-9+/_\-])[A-Za-z0-9+/_\-]{32,}={0,2}")
SECRET_NAMES = re.compile(r"(^|/)(\.env[^/]*|[^/]*\.(pem|key|p12|pfx|keychain|keychain-db|mobileprovision)|credentials[^/]*|[^/]*secret[^/]*\.json)$", re.I)


def shannon(s):
    counts = Counter(s)
    return -sum(c / len(s) * math.log2(c / len(s)) for c in counts.values())


def high_entropy(token):
    """A long token that looks random: mixed case and digits, few word-like runs, and high entropy per character.
    Hex digests, paths and identifiers are not keys."""
    t = token.rstrip("=")
    if re.fullmatch(r"[0-9a-fA-F]+", t) or re.fullmatch(r"[0-9]+", t):
        return False
    segments = [s for s in re.split(r"[/_\-]", t) if s]
    if len(segments) > 1 and all(re.fullmatch(r"[A-Za-z]*[a-z]{2,}[A-Za-z0-9]*|v?\d+(?:\.\d+)*|[A-Z0-9]{1,6}", s) for s in segments):
        return False
    upper, lower, digit = (sum(c.isupper() for c in t), sum(c.islower() for c in t), sum(c.isdigit() for c in t))
    if upper < 3 or lower < 3 or digit < 3:
        return False
    words = re.findall(r"[A-Z]?[a-z]{3,}", t)
    if sum(len(w) for w in words) > 0.45 * len(t):
        return False
    return shannon(t) >= 4.2


def key_shapes(text):
    """[(kind, line)] for every key-shaped string in a text. Never the string itself."""
    hits = []
    for kind, rx in KEY_SHAPES:
        for m in rx.finditer(text):
            hits.append((kind, text.count("\n", 0, m.start()) + 1))
    for m in TOKEN.finditer(text):
        if high_entropy(m.group(0)):
            hits.append(("a long high-entropy token", text.count("\n", 0, m.start()) + 1))
    return sorted(set(hits), key=lambda h: (h[1], h[0]))


# MARK: Files of every language

LANGS = {".swift": "swift", ".py": "python", ".sh": "shell", ".command": "shell", ".zsh": "shell", ".bash": "shell",
         ".md": "markdown", ".json": "json", ".jsonl": "json", ".toml": "toml", ".yml": "yaml", ".yaml": "yaml",
         ".html": "html", ".js": "javascript", ".css": "css", ".txt": "text"}


def lang_of(path, text):
    ext = Path(path).suffix.lower()
    if ext in LANGS:
        return LANGS[ext]
    first = text.split("\n", 1)[0]
    if first.startswith("#!"):
        return "python" if "python" in first else "shell"
    return "text"


def split_lines(text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def tag_ranges(lines, first, last, tag_rx):
    """WHAT, PIN, IN and OUT line ranges inside lines first..last (1-based), each up to the next tag."""
    tags = [(i, m.group(1)) for i in range(first, last + 1) for m in [tag_rx.match(lines[i - 1])] if m]
    ranges = {"what": None, "pin": None, "in": None, "out": None}
    for n, (start, tag) in enumerate(tags):
        stop = tags[n + 1][0] - 1 if n + 1 < len(tags) else last
        while stop > start and not re.sub(r'^[#/"\s]+|"""\s*$', "", lines[stop - 1]).strip():
            stop -= 1
        ranges[tag.lower()] = [start, stop]
    return ranges


def text_header(lang, lines):
    """The header of a shell or Python file: its leading comment block or its module docstring, with the line ranges
    of its WHAT, PIN, IN and OUT. None when the file has none."""
    if not lines:
        return None
    k = 1 if lines[0].startswith("#!") else 0
    if lang == "shell":
        start = k
        while k < len(lines) and lines[k].startswith("#"):
            k += 1
        if k == start:
            return None
        h = {"lines": [start + 1, k], "style": "hash"}
        h.update(tag_ranges(lines, start + 1, k, re.compile(r"#\s+(WHAT|PIN|IN|OUT):")))
        return h
    if lang == "python":
        while k < len(lines) and (not lines[k].strip() or lines[k].startswith("#")):
            k += 1
        if k >= len(lines) or not re.match(r'^[rubRUB]?("""|\'\'\')', lines[k]):
            return None
        quote = '"""' if '"""' in lines[k] else "'''"
        start, end = k, k
        if lines[k].count(quote) < 2:
            end = k + 1
            while end < len(lines) and quote not in lines[end]:
                end += 1
        h = {"lines": [start + 1, end + 1], "style": "doc"}
        h.update(tag_ranges(lines, start + 1, end + 1, re.compile(r'^\s*(?:[rubRUB]?""")?\s*(WHAT|PIN|IN|OUT):')))
        return h
    return None


def strip_header_line(line, style):
    if style == "swift":
        return re.sub(r"^ {0,8}", "", re.sub(r"^//(?:  (?:WHAT|PIN|IN|OUT):)?", "", line))
    if style == "hash":
        return re.sub(r"^ {0,8}", "", re.sub(r"^#(?:\s+(?:WHAT|PIN|IN|OUT):)?", "", line))
    return re.sub(r"^ {0,8}", "", re.sub(r'^\s*(?:[rubRUB]?""")?\s*(?:(?:WHAT|PIN|IN|OUT):)?', "", line)).replace('"""', "")


def first_sentence(text, cap=160):
    text = re.sub(r"\s+", " ", text or "").strip()
    cut = re.search(r"[.!?](?=\s|$)", text)
    out = text[:cut.end()] if cut else text
    return out if len(out) <= cap else out[:cap - 1].rstrip() + "…"


def what_of(lang, lines, header):
    """The first sentence a file says about itself: its WHAT, else its docstring, leading comment, description,
    title or first paragraph."""
    if header and header.get("what"):
        a, b = header["what"]
        return first_sentence(" ".join(strip_header_line(l, header.get("style", "swift")) for l in lines[a - 1:b]))
    if header and header.get("lines"):
        a, b = header["lines"]
        return first_sentence(" ".join(strip_header_line(l, header.get("style", "swift")) for l in lines[a - 1:b]))
    text = "\n".join(lines)
    if lang == "swift":
        block = []
        for l in lines:
            if l.startswith("//"):
                if not l.startswith("// swift-tools-version"):
                    block.append(l[2:])
            elif block:
                break
        return first_sentence(" ".join(block))
    if lang == "markdown":
        for para in re.split(r"\n\s*\n", text):
            p = para.strip()
            if p and not p.startswith(("#", "|", "```", "-", "*", ">")):
                return first_sentence(p)
        return ""
    if lang == "html":
        m = re.search(r'<meta name="description" content="([^"]*)"', text) or re.search(r"<title>([^<]*)</title>", text)
        return first_sentence(m.group(1)) if m else ""
    if lang in ("javascript", "css"):
        m = re.match(r"\s*/\*+\s*(.*?)\*/", text, re.S)
        return first_sentence(re.sub(r"^\s*\*\s?", "", m.group(1), flags=re.M)) if m else ""
    return ""


# MARK: The change set

HUNK = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@", re.M)


def normalize_hunk(os_, oc, ns, nc):
    """git's -U0 header to [old first, old count, new first, new count], where a zero-count side names the line
    after the gap, so a pure insertion before line 7 reads [7, 0, 7, 3]."""
    return [os_ if oc else os_ + 1, oc, ns if nc else ns + 1, nc]


def apply_hunks(old_lines, new_lines, hunks):
    """True when the hunks turn the old lines into the new ones, with equal runs between them."""
    out, i, j = [], 1, 1
    for o, oc, n, nc in hunks:
        if o - i != n - j or o < i:
            return False
        out.extend(old_lines[i - 1:o - 1])
        out.extend(new_lines[n - 1:n - 1 + nc])
        i, j = o + oc, n + nc
    if len(old_lines) - (i - 1) != len(new_lines) - (j - 1):
        return False
    out.extend(old_lines[i - 1:])
    return out == new_lines


def diff_hunks(old_path, path, old_text, new_text):
    """The hunks of a modified file, from git; checked by applying them."""
    old_lines, new_lines = split_lines(old_text), split_lines(new_text)
    raw = git("diff", "-U0", "--no-color", "--no-ext-diff", "--no-textconv", "-M", BASE, "--", *sorted({old_path, path}))
    hunks = [normalize_hunk(int(a), int(b) if b != "" else 1, int(c), int(d) if d != "" else 1) for a, b, c, d in HUNK.findall(raw)]
    if not apply_hunks(old_lines, new_lines, hunks):
        fail(f"{path}: git's hunks do not turn the base text into the working tree's; is it changing right now?")
    return hunks


def group_of(path):
    parts = path.split("/")
    if parts[0] in ("Sources", "Tests") and len(parts) > 2:
        return parts[0] + "-" + parts[1]
    return "root" if len(parts) == 1 else parts[0]


def group_key(group):
    def layer(t):
        return LAYERS.index(t) if t in LAYERS else len(LAYERS)
    if group.startswith("Sources-"):
        return (0, layer(group[8:]), group)
    if group.startswith("Tests-"):
        t = group[6:]
        return (1, layer(t[:-5] if t.endswith("Tests") else t), group)
    return ({"Playground": 2, "scripts": 3, "docs": 4, "root": 5}.get(group, 6), 0, group)


def layer_of(group):
    if group.startswith("Sources-"):
        return group[8:]
    if group.startswith("Tests-"):
        t = group[6:]
        return t[:-5] if t.endswith("Tests") else t
    return None


def exclusion(path, status):
    """Why a path is left out, by its name alone, or None."""
    if path.startswith(("docs/site/local/", "Docs/site/local/")):
        return "the ask orb's key, gitignored"
    if path.startswith("docs/site/.check/") or path.startswith("docs/site/export/"):
        return "check screenshots and exports, gitignored"
    if path.startswith("Sources/VeilGardeInference/Resources/"):
        return "the shipped bundle: a model artifact or its manifest"
    if re.match(r"^Tests/.+/Fixtures/", path):
        return "a test fixture"
    if path.endswith(".safetensors"):
        return "weights"
    if Path(path).name == "Package.resolved":
        return "a lock file, written by SwiftPM"
    if path == "LICENSE":
        return "the licence text, GPL-3.0: listed, not embedded"
    if SECRET_NAMES.search(path):
        return "a secret-shaped file name"
    return None


class Change:
    """One file of the change set: its status, its texts before and after, its hunks, and its declarations."""

    def __init__(self, status, path, old_path, new_text, old_text):
        self.status, self.path, self.old_path = status, path, old_path
        self.new, self.old = new_text, old_text
        self.group = group_of(path)
        self.lang = lang_of(path, new_text or old_text)
        self.new_lines, self.old_lines = split_lines(new_text), split_lines(old_text)
        if status == "added":
            self.hunks = [[1, 0, 1, len(self.new_lines)]] if self.new_lines else []
        elif status == "deleted":
            self.hunks = [[1, len(self.old_lines), 1, 0]] if self.old_lines else []
        elif old_text == new_text:
            self.hunks = []
        else:
            self.hunks = diff_hunks(old_path, path, old_text, new_text)
        self.swift = self.old_swift = None
        self.header = None
        if self.lang == "swift":
            if status != "deleted":
                self.swift = SwiftFile(new_text, path)
                self.header = dict(self.swift.header, style="swift") if self.swift.header else None
            if status != "added" and old_text:
                self.old_swift = SwiftFile(old_text, old_path)
        else:
            self.header = text_header(self.lang, self.new_lines if status != "deleted" else self.old_lines)
        self.what = what_of(self.lang, self.new_lines if status != "deleted" else self.old_lines, self.header)
        self.statuses, self.removed = [], []
        self.first = 0

    def touched(self, first, last):
        for o, oc, n, nc in self.hunks:
            if nc and n <= last and first <= n + nc - 1:
                return True
            if not nc and first < n <= last:
                return True
        return False

    def classify(self):
        """Each declaration added, changed (a hunk touches its lines) or unchanged; the old parse's leftovers removed."""
        if not self.swift:
            self.statuses = []
        else:
            new_tails = [i.split(":", 1)[1] for i in self.swift.ids()]
            old_tails = set(i.split(":", 1)[1] for i in self.old_swift.ids()) if self.old_swift else set()
            for sc, tail in zip(self.swift.scopes, new_tails):
                if self.status == "added" or tail not in old_tails:
                    self.statuses.append("added")
                else:
                    first = sc["doc"][0] if sc["doc"] else sc["decl"]
                    self.statuses.append("changed" if self.touched(first, sc["end"] or sc["sig"]) else "unchanged")
        if self.old_swift:
            new_tails = set(i.split(":", 1)[1] for i in self.swift.ids()) if self.swift else set()
            for k, (sc, id_) in enumerate(zip(self.old_swift.scopes, self.old_swift.ids(self.path))):
                if id_.split(":", 1)[1] not in new_tails:
                    self.removed.append({"path": self.path, "id": id_, "kind": sc["kind"], "decl": sc["decl"],
                                         "end": sc["end"] or sc["sig"], "label": self.old_swift.qualified(k)})

    def record(self, keep_old=True):
        rec = {"path": self.path, "status": self.status, "lang": self.lang, "hunks": self.hunks, "header": self.header,
               "marks": self.swift.marks if self.swift else [], "first": self.first,
               "scopes": self.swift.rows(self.statuses) if self.swift else []}
        if self.old_swift:
            rec["oldScopes"] = self.old_swift.rows(["unchanged"] * len(self.old_swift.scopes))
        if self.old_path and self.old_path != self.path:
            rec["from"] = self.old_path
        rec["old"] = self.old if keep_old else None
        rec["new"] = self.new
        return rec


def change_set():
    """[(status, path, old path)] from the base to the working tree, untracked files included, sorted by path."""
    entries = {}
    parts = git("diff", "--name-status", "-M", "-z", "--no-color", BASE).split("\0")
    i = 0
    while i < len(parts) and parts[i]:
        code = parts[i]
        if code[0] in "RC":
            old, new = parts[i + 1], parts[i + 2]
            entries[new] = ("renamed" if code[0] == "R" else "added", new, old if code[0] == "R" else None)
            i += 3
        else:
            path = parts[i + 1]
            entries[path] = ({"A": "added", "D": "deleted"}.get(code[0], "modified"), path, None if code[0] == "A" else path)
            i += 2
    for path in git("ls-files", "--others", "--exclude-standard", "-z").split("\0"):
        if path and path not in entries:
            entries[path] = ("added", path, None)
    return [entries[p] for p in sorted(entries)]


def ignored(paths):
    if not paths:
        return set()
    r = subprocess.run(["git", "-C", str(REPO), "check-ignore", "--no-index", "-z", "--stdin"], input="\0".join(paths).encode(),
                       capture_output=True, env=GIT_ENV)
    return {p for p in r.stdout.decode("utf-8", "surrogateescape").split("\0") if p}


def read_text(raw):
    """UTF-8 text, or None for a binary."""
    if b"\0" in raw[:8192]:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def collect(warnings):
    """The change set, read: the files to embed as Change objects, and the excluded ones with their reasons."""
    entries = change_set()
    gitignored = ignored([p for _, p, _ in entries])
    changes, excluded = [], []
    for status, path, old_path in entries:
        if path.startswith(OWN_OUTPUT):
            continue  # the site's own data is this build's output, not part of the change it describes
        disk = REPO / path
        size = disk.stat().st_size if status != "deleted" and disk.exists() and not disk.is_symlink() else 0
        reason = exclusion(path, status)
        if not reason and path in gitignored:
            reason = "gitignored"
        if not reason and status != "deleted" and disk.is_symlink():
            reason = "a symbolic link"
        new_raw = old_raw = b""
        if not reason:
            if status != "deleted":
                if not disk.is_file():
                    continue
                new_raw = disk.read_bytes()
            if old_path:
                old_raw = git("show", f"{BASE}:{old_path}", binary=True)
            if status == "deleted":
                size = len(old_raw)
            new_text, old_text = read_text(new_raw), read_text(old_raw)
            if new_text is None or old_text is None:
                reason = "binary"
            else:
                shapes = key_shapes(new_text) + key_shapes(old_text)
                if shapes:
                    kind, line = shapes[0]
                    reason = f"holds a key-shaped string: {kind}, line {line}"
                    warnings.append(f"{path}: left out, it holds {kind} at line {line} (the string is not printed)")
        if reason:
            excluded.append({"path": path, "bytes": size, "status": status, "reason": reason})
            continue
        changes.append(Change(status, path, old_path, new_text, old_text))
    changes.sort(key=lambda c: (group_key(c.group), c.path))
    return changes, excluded


