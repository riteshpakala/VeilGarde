    keep_old = {c.path: True for c in changes}
    outputs = assemble(changes, groups, keep_old, index, ledger)
    size = sum(len(t.encode("utf-8")) for t in outputs.values())
    if size > CAP_MB * 1048576:
        for c in sorted((c for c in changes if c.status in ("modified", "renamed")), key=lambda c: sum(h[1] + h[3] for h in c.hunks)):
            keep_old[c.path] = False
