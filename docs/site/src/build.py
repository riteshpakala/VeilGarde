def raises(fn):
    try:
        fn()
    except Failure:
        return True
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check-only", action="store_true", help="parse, resolve the trails, print the totals; write nothing")
    parser.add_argument("--self-test", action="store_true", help="the parser, the hunks and the key scan against the hard shapes")
    parser.add_argument("--dump", help="print one Swift file's scopes")
    parser.add_argument("--stats", action="store_true", help="unresolved and likely call names, id collisions, what was left out")
    args = parser.parse_args()
    try:
        if args.self_test:
            sys.exit(0 if self_test() else 1)
        if args.dump:
            dump(args.dump)
            return
        outputs, changes = build(stats=args.stats)
        if not args.check_only and not args.stats:
            write(outputs, changes)
    except Failure as e:
        print(f"build: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
