def ask(page, rel):
    """The orb, used: half seen, whole under the pointer, open into a chat, answer through a stand-in, read one
    declaration on the explorer, start a new chat, close back. No request leaves the browser."""
    errors = []
    try:
        page.wait_for_selector(".ask-orb", state="attached", timeout=5000)
    except Exception:
        return ["the ask orb never appeared"]
    page.evaluate("window.scrollTo(0, 0)")
    page.mouse.move(5, 5)
    page.wait_for_timeout(300)
    orb = page.query_selector(".ask-orb")
    rest = float(orb.evaluate("e => getComputedStyle(e).opacity"))
    orb.hover()
    page.wait_for_timeout(350)
    lit = float(orb.evaluate("e => getComputedStyle(e).opacity"))
    if abs(rest - 0.5) > 0.01 or lit < 0.99:
        errors.append(f"the orb shows at {rest} and at {lit} under the pointer, not 0.5 and 1")
    page.evaluate("""() => { VeilGarde.__bodies = []; VeilGarde.ask.transport = (body, key, onDelta) => {
        VeilGarde.__bodies.push(JSON.parse(JSON.stringify(body)));
        if (body.tools && !body.messages.some(m => m.role === "tool"))
            return Promise.resolve({ content: "", toolCalls: [{ id: "abcdefghi", type: "function", function: { name: "read_declaration", arguments: '{"name":"Detector.detect"}' } }] });
        onDelta("It **routes** the image. See `Detector.detect` at Detector.swift:42."); return Promise.resolve({ content: "", toolCalls: [] }); };
        window.VeilGardeData.ask = { provider: "mistral", model: "mistral-large-4", reasoning: "none", key: "stand-in", source: "a stand-in for the check" }; }""")
    orb.click()
    try:
        page.wait_for_selector(".ask:not([hidden]) .ask-form textarea:not([disabled])", timeout=5000)
    except Exception:
        return errors + ["the orb did not open into a chat with its box enabled"]
    opened = page.evaluate("() => ({ orb: document.querySelector('.ask-orb').hidden, focus: !!document.activeElement && document.activeElement.matches('.ask textarea'), about: document.querySelector('.ask-about').textContent })")
    if not opened["orb"] or not opened["focus"]:
        errors.append(f"opening the orb left {opened}")
    page.keyboard.type("What does this do?", delay=5)
    page.keyboard.press("Enter")
    try:
        page.wait_for_function("document.querySelectorAll('.ask-msg.bot b').length > 0", timeout=5000)
    except Exception:
        return errors + ["no answer came back from the stand-in"]
    bodies = page.evaluate("() => VeilGarde.__bodies")
    sent = bodies[0]["messages"] if bodies else None
    if not sent or sent[0]["role"] != "system" or sent[-1] != {"role": "user", "content": "What does this do?"}:
        errors.append(f"the chat sent {str(sent)[:200]}")
        return errors
    first = bodies[0]
    if first.get("stream") is not True or first.get("model") != "mistral-large-4" or first.get("reasoning_effort") != "none":
        errors.append(f"the request is not a streamed mistral-large-4 request with reasoning off: {[first.get(k) for k in ('stream', 'model', 'reasoning_effort')]}")
    if rel in ASK:
        heading, count = ASK[rel]
        label = page.evaluate("document.getElementById('explorer').getAttribute('data-scope')").split(":", 1)[1].split("(")[0]
        if label not in sent[0]["content"] or heading not in sent[0]["content"] or len(first.get("tools") or []) != count:
            errors.append(f"the first request lacks the selected {label}, the map headed {heading!r} or the {count} tools")
