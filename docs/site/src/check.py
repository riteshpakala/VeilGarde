def load_data(problems):
    """The values the generated data files assign, after checking each is exactly the shape build.py writes."""
    out = {"files": {}}
    for p in sorted(DATA.rglob("*.js")) if DATA.is_dir() else []:
        rel = p.relative_to(SITE).as_posix()
        text = p.read_text(encoding="utf-8")
        lines = text.split("\n")
        group = rel.startswith("data/files/")
        want = 5 if group else 4
        if len(lines) != want or lines[0] != HEADER or lines[1] != GUARD or lines[-1] != "" or (group and lines[2] != FILES_GUARD):
            problems.append(f"{rel}: not the shape docs/site/src/build.py writes; run docs/site/src/build.sh")
            continue
        m = re.match(r'^window\.VeilGardeData\.(run|index) = (.*);$', lines[2]) if not group else re.match(r'^window\.VeilGardeData\.files\["([\w-]+)"\] = (.*);$', lines[3])
        if not m:
            problems.append(f"{rel}: not the shape docs/site/src/build.py writes; run docs/site/src/build.sh")
            continue
        value = json.loads(m.group(2))
        if json.dumps(value, ensure_ascii=False, separators=(",", ":")) != m.group(2):
            problems.append(f"{rel}: its JSON is not as build.py writes it; run docs/site/src/build.sh")
        if group:
            if m.group(1) != p.stem:
                problems.append(f"{rel}: assigns the group {m.group(1)}")
            out["files"][m.group(1)] = value
        else:
            out[m.group(1)] = value
    if "index" not in out or "run" not in out:
        problems.append("data/index.js or data/run.js is missing; run docs/site/src/build.sh")
    return out


def check_data(data, problems):
    """Every embedded text equals the working tree and the base; the change set, the ledger and the trails have not
    moved since the build; the data is under its cap."""
    index = data.get("index")
    if not index:
        return
    size = sum(p.stat().st_size for p in DATA.rglob("*.js"))
    print(f"  data: {size / 1048576:.2f} MB of {CAP_MB:g} MB in {len(list(DATA.rglob('*.js')))} files")
    if size > CAP_MB * 1048576:
        problems.append(f"data: {size / 1048576:.2f} MB, over its {CAP_MB} MB cap")
    if set(index["groups"]) != set(data["files"]):
        problems.append(f"data/files holds {sorted(data['files'])}, the index names {index['groups']}; run docs/site/src/build.sh")
    records = [f for g in index["groups"] for f in data["files"].get(g, {}).get("files", [])]
    if [f["path"] for f in records] != [f["path"] for f in index["files"]]:
        problems.append("the index and the group files list different files; run docs/site/src/build.sh")
    stale = 0
    for f in records:
        disk = REPO / f["path"]
        if f["status"] != "deleted":
            if not disk.is_file() or disk.read_bytes() != f["new"].encode("utf-8"):
                problems.append(f"{f['path']} has changed since the site was built; run docs/site/src/build.sh")
                stale += 1
        if f.get("old") is not None and f["status"] != "added":
            if git("show", f"{BASE}:{f.get('from') or f['path']}", binary=True) != f["old"].encode("utf-8"):
                problems.append(f"{f['path']}: its base text in the data is not the base commit's")
    names = git("diff", "--name-only", "-M", "-z", BASE).split("\0") + git("ls-files", "--others", "--exclude-standard", "-z").split("\0")
    now = {n for n in names if n and not n.startswith("docs/site/data/")}
    then = {f["path"] for f in index["files"]} | {x["path"] for x in index["excluded"]}
    if now != then:
        added, gone = sorted(now - then), sorted(then - now)
        problems.append(f"the change set has moved since the build: {len(added)} new ({', '.join(added[:4])}{'…' if len(added) > 4 else ''}), "
                        f"{len(gone)} gone ({', '.join(gone[:4])}); run docs/site/src/build.sh")
    try:
        ledger = json.loads((SITE / "src" / "ledger.json").read_text(encoding="utf-8"))
        if ledger != data.get("run"):
            problems.append("docs/site/src/ledger.json has changed since the build; run docs/site/src/build.sh")
        trails = json.loads((SITE / "src" / "trails.json").read_text(encoding="utf-8"))
        if trail_tuples(trails) != trail_tuples(index, built=True):
            problems.append("docs/site/src/trails.json has changed since the build; run docs/site/src/build.sh")
        ml_file = SITE / "src" / "mltrails.json"
        if ml_file.is_file() != bool(index.get("ml")):
            problems.append("docs/site/src/mltrails.json and the data disagree on whether the ML explorer has trails; run docs/site/src/build.sh")
        elif ml_file.is_file() and trail_tuples(json.loads(ml_file.read_text(encoding="utf-8"))) != trail_tuples(index["ml"], built=True):
            problems.append("docs/site/src/mltrails.json has changed since the build; run docs/site/src/build.sh")
    except (OSError, ValueError, KeyError) as e:
        problems.append(f"the ledger or the trails cannot be read: {e}")
    print(f"  data: {len(records)} embedded files, {stale} changed since the build, {len(index['excluded'])} left out and listed")


def trail_tuples(spec, built=False):
    """A trail file, or the data built from it, as the fields a reader sees: each entry's trail, say, chapters, anchor,
    note and cite, an ML step's primer and lane, an ML entry's deeper line, facts and twins, each trail's lanes, the
    picker and the declared kinds. The two must be equal, or the data is stale."""
    out = []
    for t in spec.get("trails", []):
        out.append((t["id"], [(x["id"], x["label"]) for x in t.get("lanes") or []]))
        for s in t["steps"]:
            for e in s["entries"]:
                d = e.get("deeper") or {}
                out.append((t["id"], t["say"], s.get("chapters", []), e["anchor"], e["note"].strip(), e.get("cite", ""), (s.get("primer") or "").strip() or None,
                            s.get("lane"), (d.get("text") or "").strip() or None, d.get("cite"), e.get("facts"), e.get("code")))
    out.append([(s["title"], [c["kind"] for c in s["columns"]] if built else s["kinds"], [(r["label"], r["trails"]) for r in s["rows"]]) for s in spec.get("picker", [])])
    out.append([(k["id"], k["label"]) for k in spec.get("kinds") or []])
    return out


