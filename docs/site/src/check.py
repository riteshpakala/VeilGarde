def git(*args, binary=False):
    r = subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, env=GIT_ENV)
    return r.stdout if binary else r.stdout.decode("utf-8", "surrogateescape")


def site_files(pattern):
    for p in sorted(SITE.rglob(pattern)):
        rel = p.relative_to(SITE).as_posix()
        if rel.startswith(IGNORED) or p.name.startswith("._"):
            continue
        yield p


def pages(selected=None):
    out = list(site_files("*.html"))
    if selected:
        wanted = set(selected.split(","))
        out = [p for p in out if p.name in wanted or p.relative_to(SITE).as_posix() in wanted]
    return out


