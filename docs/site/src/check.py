class Collector(html.parser.HTMLParser):
    SKIP_TAGS = ("details", "pre", "code", "table", "script", "style", "svg", "blockquote")
    SKIP_CLASSES = ("code", "engineers", "note", "facts")

    def __init__(self):
        super().__init__()
        self.ids, self.links, self.srcs, self.paragraphs = set(), [], [], []
        self._stack, self._buf, self._skip = [], [], 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            self.ids.add(a["id"])
        if tag == "a" and "href" in a:
            self.links.append(a["href"])
        if tag in ("script", "link", "img") and (a.get("src") or a.get("href")):
            self.srcs.append(a.get("src") or a.get("href"))
        if tag in ("br", "img", "meta", "link", "input", "hr"):
            return
        classes = (a.get("class") or "").split()
        if tag in self.SKIP_TAGS or any(c in classes for c in self.SKIP_CLASSES):
            self._skip += 1
            self._stack.append(("skip", tag))
        elif tag in ("p", "figcaption", "li") and self._skip == 0:
            self._stack.append(("para", tag))
            self._buf = []
        else:
            self._stack.append(("other", tag))

    def handle_endtag(self, tag):
        while self._stack:
            kind, t = self._stack.pop()
            if kind == "skip":
                self._skip -= 1
            if kind == "para" and t == tag and self._skip == 0:
                text = re.sub(r"\s+", " ", "".join(self._buf)).strip()
                if text:
                    self.paragraphs.append(text)
            if t == tag:
                break

    def handle_data(self, data):
        if self._skip == 0:
            self._buf.append(data)


def collect(path):
    c = Collector()
    c.feed(path.read_text(encoding="utf-8"))
    return c


def check_links(data, problems):
    index = data.get("index") or {}
    paths = {f["path"] for f in index.get("files", [])}
    ledger = data.get("run") or {}
    ledger_ids = {x["id"] for k in ("amendments", "answers", "decisions", "commands", "tests", "assumptions", "questions") for x in ledger.get(k, []) or []}
    # The trail steps each explorer answers: the code's on code.html, the models' on ml.html.
    trail_steps = {"code.html": {t["id"]: len(t["steps"]) for t in index.get("trails", [])},
                   "ml.html": {t["id"]: len(t["steps"]) for t in (index.get("ml") or {}).get("trails", [])}}
    first_steps = len(index["trails"][0]["steps"]) if index.get("trails") else 0
    ids = {p: collect(p).ids for p in site_files("*.html")}
    for page in site_files("*.html"):
        info, rel = collect(page), page.relative_to(SITE).as_posix()
        for src in info.srcs:
            if not re.match(r"^(https?:|//|/)", src) and not (page.parent / src.split("#")[0].split("?")[0]).exists():
                problems.append(f"{rel}: {src} does not resolve")
        for href in info.links:
            if re.match(r"^(https?:|mailto:|//)", href):
                problems.append(f"{rel}: a link leaves the site, {href}")
                continue
            target, _, frag = href.partition("#")
            dest = (page.parent / target).resolve() if target else page
            if target and not dest.exists():
                problems.append(f"{rel}: the link {href} does not resolve")
                continue
            if not frag or dest.suffix != ".html":
                continue
            frag = frag.split(";")[0] if not frag.startswith("trail-") else frag
            if dest.name in trail_steps and frag not in ids.get(dest, set()):
                m = re.match(r"^trail-([a-z]+(?:-[a-z]+)*)-(\d+)(?:;n=(\d+))?$", frag)
                if m:
                    if not 1 <= int(m.group(2)) <= trail_steps[dest.name].get(m.group(1), 0):
                        problems.append(f"{rel}: #{frag} is not a step of a trail on {dest.name}")
                    continue
                if re.match(r"^trail-\d+", frag):
                    problems.append(f"{rel}: #{frag} is the one trail's old link form; name the trail")
                    continue
                if frag.startswith("q="):
                    continue
                path, _, at = frag.partition(":") if not frag in paths else (frag, "", "")
                if path not in paths:
                    problems.append(f"{rel}: #{frag} names a file that is not in the change")
                elif at.isdigit():
                    f = next(x for x in index["files"] if x["path"] == path)
                    if not 1 <= int(at) <= f["lines"]:
                        problems.append(f"{rel}: #{frag} is past the end of {path}")
                elif at:
                    group = next(x["group"] for x in index["files"] if x["path"] == path)
                    rec = next((x for x in data["files"].get(group, {}).get("files", []) if x["path"] == path), None)
                    if rec is not None and not any(sc[1] == at.split(".")[-1].split("(")[0] for sc in rec["scopes"]):
                        problems.append(f"{rel}: #{frag} names no declaration in {path}")
                continue
            if dest.name == "index.html" and (LEDGER_IDS.match(frag) and frag in ledger_ids or re.match(r"^step-\d+$", frag) and 1 <= int(frag[5:]) <= first_steps):
                continue
            if frag not in ids.get(dest, set()):
                problems.append(f"{rel}: #{frag} is not an id in {dest.name}")


def check_lint(problems):
    for p in list(site_files("*.html")) + list(site_files("*.js")) + list(site_files("*.css")):
        text = p.read_text(encoding="utf-8")
        rel = p.relative_to(SITE).as_posix()
        if re.search(r"""type=["']module["']""", text):
            problems.append(f"{rel}: an ES module (file:// blocks them)")
        if p.suffix == ".js" and re.search(r"^\s*(import|export)\s", text, re.M):
            problems.append(f"{rel}: an import or export statement")
        if rel == "js/ask.js":
            urls = set(re.findall(r"https?://[^\s\"'`)]+", text))
            if urls != {ENDPOINT}:
                problems.append(f"{rel}: the orb may call {ENDPOINT} and nothing else; it names {sorted(urls)}")
            if len(re.findall(r"\bfetch\s*\(", text)) != 1 or not re.search(r"\bfetch\(ENDPOINT,", text):
                problems.append(f"{rel}: fetch must appear once, to ENDPOINT")
        elif re.search(r"\bfetch\s*\(", text):
            problems.append(f"{rel}: fetch() outside js/ask.js (file:// blocks it)")
        for m in re.finditer(r"""(?:src|href)\s*=\s*["'](https?://[^"']+)""", text):
            problems.append(f"{rel}: a network URL {m.group(1)}")
        for m in re.finditer(r"""url\((['"]?)(https?://[^)'"]+)""", text):
            problems.append(f"{rel}: a network URL {m.group(2)}")
        if re.search(r"""(?:src|href)=["']/(?!/)""", text):
            problems.append(f"{rel}: an absolute path")
        if "@import" in text:
            problems.append(f"{rel}: an @import")
        if p.suffix == ".js":
            for m in re.finditer(r"\bwindow\.([A-Za-z_$][\w$]*)\s*=(?!=)", text):
                if m.group(1) not in GLOBALS:
                    problems.append(f"{rel}: a third global, window.{m.group(1)}")
            if not re.match(r"\s*/\*", text):
                problems.append(f"{rel}: no header comment saying what it is")
            body = re.sub(r"/\*.*?\*/", "", text, count=1, flags=re.S).strip()
            if not body.startswith("(function () {") or not body.rstrip().endswith("})();"):
                problems.append(f"{rel}: not one function wrapped around its code, so its names could leak as globals")


def check_local(problems):
    """docs/site/local/ holds the orb's key. Git must ignore it, in both spellings of the folder, and track nothing in it."""
    for spelling in ("docs/site/local/ask.js", "Docs/site/local/ask.js"):
        if subprocess.run(["git", "-C", str(REPO), "check-ignore", "-q", spelling], env=GIT_ENV).returncode != 0:
            problems.append(f"{spelling} is not ignored by git; it holds an API key")
    tracked = git("ls-files", "docs/site/local", "Docs/site/local").split()
    if tracked:
        problems.append(f"git tracks {', '.join(tracked)}, which holds an API key; remove it from the index and rotate the key")
    key_file = SITE / "local" / "ask.js"
    if key_file.exists() and key_file.stat().st_mode & 0o077:
        problems.append("docs/site/local/ask.js is readable by others; askkey.py writes it with mode 600")
    print(f"  local: git ignores docs/site/local/ask.js; it {'exists, mode 600' if key_file.exists() else 'is not written'}")


def mistral_key():
    env = os.environ.get("MISTRAL_API_KEY", "").strip()
    if env:
        return env
    try:
        entry = json.loads((Path.home() / ".rao" / "keys" / "providers.json").read_text(encoding="utf-8")).get("MISTRAL_API_KEY") or {}
        return (entry.get("value") or "").strip() if isinstance(entry, dict) else ""
    except (OSError, ValueError, AttributeError):
        return ""


def check_key(problems):
    """Every file git can see, scanned for the key's value. Only the number of hits is printed, never the key."""
    key = mistral_key()
    if not key:
        print("  key scan: no Mistral key on this Mac to scan for")
        return
    needle = key.encode("utf-8")
    files = [f for f in git("ls-files", "--cached", "--others", "--exclude-standard", "-z").split("\0") if f]
    hits = 0
    for f in files:
        p = REPO / f
        try:
            if p.is_file() and not p.is_symlink() and needle in p.read_bytes():
                hits += 1
        except OSError:
            pass
    print(f"  key scan: {len(files)} files git can see, {hits} hold the key's value")
    if hits:
        problems.append(f"{hits} files git can see hold the Mistral key's value; remove it from them and rotate the key")


def check_prose(problems, warnings, verbose):
    for p in site_files("*.html"):
        rel = p.relative_to(SITE).as_posix()
        for para in collect(p).paragraphs:
            low = para.lower()
            for phrase in BANNED:
                if re.search(r"\b" + re.escape(phrase) + r"\b", low):
                    problems.append(f"{rel}: “{phrase}” in “{para[:70]}…”")
            if re.search(r"\([^)]*[a-z][^)]*\)", para) and not re.search(r"\b[A-Za-z_]+\([^)]*\)", para):
                problems.append(f"{rel}: a parenthesis inside a paragraph: “{para[:70]}…”")
            sentences = [s for s in re.split(r"(?<=[.!?])\s+(?=[A-Z“\"])", para) if s]
            for s in sentences:
                if len(s.split()) > 30:
                    warnings.append(f"{rel}: a sentence of {len(s.split())} words: “{s[:60]}…”")
            if len(sentences) > 5:
                warnings.append(f"{rel}: a paragraph of {len(sentences)} sentences: “{para[:50]}…”")
            numbers = re.findall(r"(?<![\w.])\d[\d,.]*\d|\b\d\b", para)
            if len(set(numbers)) > 3:
                warnings.append(f"{rel}: {len(set(numbers))} numbers in one paragraph: “{para[:50]}…”")
    if verbose:
        for w in warnings:
            print("  prose:", w)


