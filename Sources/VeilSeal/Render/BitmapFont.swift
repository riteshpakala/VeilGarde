//  WHAT: A 5 × 7 pixel font for the digests' and overlays' captions, drawn as filled squares, so a
//        rendered PNG is the same bytes on every Mac (CoreText is not an import this package allows,
//        and antialiased text would not pin).
//  PIN:  Each glyph is seven rows of five bits, the leftmost the high bit; the advance is six cells.
//        Typographic quotes and dashes draw as their typewriter twins (a summary's “label” reads as
//        "LABEL", not ?LABEL?); lowercase draws as uppercase; anything else without a glyph draws as "?".
//

