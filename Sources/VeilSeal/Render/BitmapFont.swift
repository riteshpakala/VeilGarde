    /// Typographic punctuation and the typewriter glyph it draws as.
    static let aliases: [Character: Character] = ["“": "\"", "”": "\"", "‘": "'", "’": "'", "–": "-", "—": "-"]

    static func glyph(_ ch: Character) -> [UInt8] {
        let ch = aliases[ch] ?? ch
        if let g = glyphs[ch] { return g }
        if let upper = String(ch).uppercased().first, let g = glyphs[upper] { return g }
        return glyphs["?"]!
    }

    /// The width `text` takes at `scale` (cells of scale × scale pixels).
    static func width(_ text: String, scale: Int) -> Int { max(0, text.count * advance * scale - scale) }

    /// `text` cut with an ellipsis to fit `pixels` at `scale`.
    static func fitted(_ text: String, pixels: Int, scale: Int) -> String {
        let room = max(1, (pixels + scale) / (advance * scale))
        return text.count <= room ? text : String(text.prefix(max(0, room - 1))) + "…"
    }
